//! Two jobs at build time.
//!
//! 1. Places the sideloaded ConPTY (`third_party/conpty`) next to the built binaries on Windows
//!    so portable-pty loads the modern `conpty.dll` + `OpenConsole.exe` instead of the slow
//!    inbox ConPTY of Windows 10.
//! 2. Embeds the phone client (`app/dist-phone`, built by `pnpm build:phone`) in the daemon, which serves it
//!    to phones. Without the bundle a development build embeds a placeholder page; a release build
//!    (`KELPIE_REQUIRE_PHONE=1`, set by `scripts/build-release.sh` and both workflows) refuses to.
use std::fmt::Write as _;
use std::path::{Path, PathBuf};

/// What a phone is shown when this daemon was built without the phone client. A release is checked for this
/// string (`.github/workflows/release.yml`), so it appears in the binary only in that case.
const PLACEHOLDER_MARKER: &str = "KELPIE_PHONE_BUNDLE_MISSING";

fn main() {
    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-changed=../../third_party/conpty");
    sideload_conpty();
    embed_phone_client();
}

fn sideload_conpty() {
    if std::env::var("CARGO_CFG_WINDOWS").is_err() {
        return;
    }
    let arch = match std::env::var("CARGO_CFG_TARGET_ARCH").as_deref() {
        Ok("aarch64") => "arm64",
        _ => "x64",
    };
    let src = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap())
        .join("../../third_party/conpty")
        .join(arch);
    // OUT_DIR is <cargo output>/<profile>/<scripts dir>/kelpied-<hash>/out
    let out = PathBuf::from(std::env::var("OUT_DIR").unwrap());
    let Some(profile_dir) = out.ancestors().nth(3) else { return };
    for dir in [profile_dir.to_path_buf(), profile_dir.join("examples"), profile_dir.join("deps")] {
        let _ = std::fs::create_dir_all(&dir);
        for file in ["conpty.dll", "OpenConsole.exe"] {
            let from = src.join(file);
            let to = dir.join(file);
            let size = |p: &PathBuf| std::fs::metadata(p).map(|m| m.len()).ok();
            if size(&from) != size(&to) {
                // A running daemon may hold the old copy open; it keeps working, so ignore.
                let _ = std::fs::copy(&from, &to);
            }
        }
    }
}

fn embed_phone_client() {
    println!("cargo:rerun-if-env-changed=KELPIE_REQUIRE_PHONE");
    println!("cargo:rerun-if-env-changed=KELPIE_PHONE_DIST");
    // KELPIE_PHONE_DIST points the build at another folder (scripts/check-phone-guard.sh proves the guard with an empty one).
    let dir = match std::env::var_os("KELPIE_PHONE_DIST") {
        Some(other) => PathBuf::from(other),
        None => PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap()).join("../../app/dist-phone"),
    };
    // Watched as a directory (every file in it). Created when missing so that cargo has something that
    // exists to watch: a path that does not exist counts as changed on every build, and the daemon would
    // be rebuilt each time in a checkout that never built the client.
    let _ = std::fs::create_dir_all(&dir);
    println!("cargo:rerun-if-changed={}", dir.display());

    let mut files = Vec::new();
    if dir.join("index.html").is_file() {
        collect(&dir, &dir, &mut files);
        files.sort();
    } else if std::env::var("KELPIE_REQUIRE_PHONE").is_ok_and(|v| v == "1") {
        println!("cargo:warning=app/dist-phone/index.html is missing and KELPIE_REQUIRE_PHONE=1");
        panic!("the phone client is not built: run `pnpm build:phone` in app/ before building kelpied (KELPIE_REQUIRE_PHONE=1 is set)");
    }

    let mut table = String::new();
    if files.is_empty() {
        let page = format!(
            "<!doctype html><meta charset=utf-8><meta name=viewport content=\"width=device-width,initial-scale=1\"><title>Kelpie</title>\
             <body><h1>Kelpie</h1>\
             <p>This Kelpie daemon was built without its phone client (<code>{PLACEHOLDER_MARKER}</code>).</p>\
             <p>Run <code>pnpm build:phone</code> in <code>app/</code> and build the daemon again.</p>"
        );
        let _ = writeln!(table, "    (\"/index.html\", \"text/html; charset=utf-8\", {page:?}.as_bytes()),");
    } else {
        for rel in &files {
            let path = dir.join(rel.trim_start_matches('/'));
            let _ = writeln!(table, "    ({rel:?}, {:?}, include_bytes!({:?})),", mime(rel), path.to_string_lossy());
        }
    }
    let code = format!(
        "/// The phone client, as (path, content type, bytes). Generated by build.rs from app/dist-phone.\n\
         pub static PHONE_ASSETS: &[(&str, &str, &[u8])] = &[\n{table}];\n"
    );
    let out = PathBuf::from(std::env::var("OUT_DIR").unwrap()).join("phone_assets.rs");
    // Not rewritten when it would not change, so that a rerun of this script does not recompile the daemon.
    if std::fs::read_to_string(&out).ok().as_deref() != Some(&code) {
        std::fs::write(&out, code).expect("write phone_assets.rs");
    }
}

/// Every file under `dir`, as `/relative/path`.
fn collect(root: &Path, dir: &Path, out: &mut Vec<String>) {
    let Ok(entries) = std::fs::read_dir(dir) else { return };
    for entry in entries.flatten() {
        let path = entry.path();
        if path.is_dir() {
            collect(root, &path, out);
        } else if let Ok(rel) = path.strip_prefix(root) {
            // Source maps are not served.
            if path.extension().is_some_and(|e| e == "map") {
                continue;
            }
            out.push(format!("/{}", rel.to_string_lossy().replace('\\', "/")));
        }
    }
}

fn mime(path: &str) -> &'static str {
    match path.rsplit('.').next().unwrap_or("") {
        "html" => "text/html; charset=utf-8",
        "js" | "mjs" => "text/javascript; charset=utf-8",
        "css" => "text/css; charset=utf-8",
        "svg" => "image/svg+xml",
        "webmanifest" => "application/manifest+json",
        "json" => "application/json",
        "png" => "image/png",
        "ico" => "image/x-icon",
        "woff2" => "font/woff2",
        "txt" => "text/plain; charset=utf-8",
        _ => "application/octet-stream",
    }
}
