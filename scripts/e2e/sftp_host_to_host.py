"""E2E for host-to-host copies through an isolated daemon (no window).

    python -X utf8 scripts/e2e/sftp_host_to_host.py <kelpied.exe> <scratch-dir>

Sets its own KELPIE_ENDPOINT, KELPIE_DATA_DIR and KELPIE_SSH_DIR in this process before anything starts, and starts its
own `kelpied serve`. Two `ssh_test_server.py` instances (needs paramiko) play host A and host B, each with its own
$HOME (KELPIE_TEST_HOME), so A's ~/.ssh is a scratch folder; B is also reachable through a throttled
`net_fault_proxy.py`. The real ~/.ssh, agent and daemon are never touched; only processes this script starts are
stopped, by their own handles (or by PID when they are this run's ssh / sftp).

Covers:
1. A has a key and B's host key: the copy goes direct, the file arrives with the same SHA-256.
2. The outer ssh to A has ForwardAgent=no even though the host's config says ForwardAgent yes.
3. Cancel of a direct copy: no partial on B, no sftp left running for it.
4. B goes away mid-copy and comes back: the direct copy resumes (reput) and the hash is equal.
4b. An empty file, a name with a quote and spaces, and one with `$(...)` go direct and run nothing anywhere.
5. A without a login of its own on B: the copy goes through this computer, with that reason, and the hash is equal.
"""
import hashlib
import importlib.util
import os
import shutil
import subprocess
import sys
import time

kelpied, scratch = os.path.abspath(sys.argv[1]), os.path.abspath(sys.argv[2])
HERE = os.path.dirname(os.path.abspath(__file__))
PORT_A, PORT_B, SLOW_B = 47921, 47922, 47923
BASH = os.environ.get("KELPIE_TEST_BASH", r"C:\Program Files\Git\bin\bash.exe")

os.environ["KELPIE_ENDPOINT"] = f"kelpie-e2e-h2h-{os.getpid()}"
data, ssh_dir = os.path.join(scratch, "data"), os.path.join(scratch, "ssh")
home_a, home_b = os.path.join(scratch, "home-a"), os.path.join(scratch, "home-b")
os.environ["KELPIE_DATA_DIR"] = data
os.environ["KELPIE_SSH_DIR"] = ssh_dir
# The Files tab's home is a scratch folder too: nothing lands in the real profile.
os.environ["KELPIE_FILES_HOME"] = os.path.join(scratch, "files-home")
# The e2e's hosts all live on this computer: there a local address is the same machine, so it may go direct.
os.environ["KELPIE_E2E"] = "1"
for d in (data, ssh_dir, home_a, home_b):
    shutil.rmtree(d, ignore_errors=True)
    os.makedirs(d)
for d in (os.path.join(home_a, ".ssh"), os.path.join(home_b, ".ssh"), os.path.join(data, "ssh")):
    os.makedirs(d, exist_ok=True)
if os.name == "nt":
    for d in (ssh_dir, os.path.join(data, "ssh")):
        subprocess.run(["icacls", d, "/inheritance:r", "/grant:r", f"{os.environ['USERNAME']}:(OI)(CI)F", "/grant:r", "SYSTEM:(OI)(CI)F", "/grant:r", "Administrators:(OI)(CI)F"], capture_output=True, check=True)

spec = importlib.util.spec_from_file_location("kelpie_call", os.path.join(HERE, "..", "kelpie-call.py"))
kc = importlib.util.module_from_spec(spec)
spec.loader.exec_module(kc)
import paramiko  # noqa: E402

fwd = lambda p: p.replace("\\", "/")
q = lambda p: f'"{fwd(p)}"'
keygen = os.path.join(os.environ.get("SystemRoot", r"C:\Windows"), "System32", "OpenSSH", "ssh-keygen.exe") if os.name == "nt" else "ssh-keygen"
key = os.path.join(ssh_dir, "id_e2e")
subprocess.run([keygen, "-q", "-t", "ed25519", "-N", "", "-f", key], check=True)
# A's own key for B, in A's ~/.ssh (Git Bash's ssh on "host A" reads it).
key_a = os.path.join(home_a, ".ssh", "id_ed25519")
subprocess.run([keygen, "-q", "-t", "ed25519", "-N", "", "-f", key_a], check=True)
if os.name == "nt":
    subprocess.run([BASH, "-c", 'chmod 600 "$1"', "_", fwd(key_a)], capture_output=True)
open(os.path.join(home_b, ".ssh", "authorized_keys"), "w").write(open(key_a + ".pub").read())

host_keys = {}
for name in ("a", "b"):
    path = os.path.join(scratch, f"host_key_{name}")
    if not os.path.exists(path):
        paramiko.RSAKey.generate(2048).write_private_key_file(path)
    host_keys[name] = (path, paramiko.RSAKey(filename=path).get_base64())
# This computer trusts both; A trusts B (on its port and on the throttled one).
open(os.path.join(ssh_dir, "known_hosts"), "w").write(
    f"[127.0.0.1]:{PORT_A} ssh-rsa {host_keys['a'][1]}\n[127.0.0.1]:{PORT_B} ssh-rsa {host_keys['b'][1]}\n[127.0.0.1]:{SLOW_B} ssh-rsa {host_keys['b'][1]}\n")
open(os.path.join(home_a, ".ssh", "known_hosts"), "w").write(f"[127.0.0.1]:{PORT_B} ssh-rsa {host_keys['b'][1]}\n[127.0.0.1]:{SLOW_B} ssh-rsa {host_keys['b'][1]}\n")
open(os.path.join(ssh_dir, "empty"), "w").close()
open(os.path.join(ssh_dir, "config"), "w").close()
auth = f"  User tester\n  IdentityFile {q(key)}\n  IdentitiesOnly yes\n  IdentityAgent none\n"
with open(os.path.join(data, "ssh", "config"), "w") as f:
    f.write("# Generated by Kelpie from hosts.json (here: by the e2e script).\n")
    # The host's own config asks for agent forwarding: Kelpie's ssh to A must still never forward.
    # ... and a terminal (tmux-on-login setups): Kelpie's ssh to A must still never take one.
    f.write(f"\nHost e2e-a\n  HostName 127.0.0.1\n  Port {PORT_A}\n{auth}  ForwardAgent yes\n  RequestTTY force\n")
    f.write(f"\nHost e2e-b\n  HostName 127.0.0.1\n  Port {PORT_B}\n{auth}")
    f.write(f"\nHost e2e-b-slow\n  HostName 127.0.0.1\n  Port {SLOW_B}\n{auth}")
    f.write(f"\nHost e2e-b-other\n  HostName 127.0.0.1\n  Port {PORT_B}\n{auth}")
    f.write(f"\nMatch all\n  UserKnownHostsFile {q(os.path.join(ssh_dir, 'known_hosts'))}\n  GlobalKnownHostsFile {q(os.path.join(ssh_dir, 'empty'))}\nInclude {q(os.path.join(ssh_dir, 'config'))}\n")

py = os.environ.get("KELPIE_SSH_TEST_PYTHON", sys.executable)
started = {}


def start_server(name, port, home):
    p = subprocess.Popen([py, os.path.join(HERE, "ssh_test_server.py"), str(port), key + ".pub", host_keys[name][0]], env=dict(os.environ, KELPIE_TEST_HOME=home), stdout=subprocess.PIPE, stderr=subprocess.STDOUT)
    p.stdout.readline()
    started[name] = p


def stop(name):
    p = started.pop(name, None)
    if p and p.poll() is None:
        p.terminate()
        try:
            p.wait(10)
        except subprocess.TimeoutExpired:
            p.kill()


def processes(image):
    """(pid, command line) of running `image` processes."""
    if os.name != "nt":
        out = subprocess.run(["ps", "-A", "-o", "pid=,args="], capture_output=True, text=True).stdout
        return [(int(l.split(None, 1)[0]), l.split(None, 1)[1]) for l in out.splitlines() if image in l]
    out = subprocess.run(["powershell", "-NoProfile", "-Command", f"Get-CimInstance Win32_Process -Filter \"Name='{image}.exe'\" | ForEach-Object {{ \"$($_.ProcessId)`t$($_.CommandLine)\" }}"], capture_output=True, text=True).stdout
    return [(int(p), c) for p, _, c in (l.partition("\t") for l in out.splitlines()) if p.strip().isdigit()]


ok = True


def check(cond, what):
    global ok
    print(("PASS " if cond else "FAIL ") + what, flush=True)
    ok = ok and bool(cond)


def sha(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        while chunk := f.read(1 << 20):
            h.update(chunk)
    return h.hexdigest()


def posix(p):
    return "/" + p[0].lower() + fwd(p[2:]) if len(p) > 1 and p[1] == ":" else fwd(p)


def wait_job(c, jid, cond, timeout=300):
    end = time.time() + timeout
    while time.time() < end:
        j = next(j for j in c.call("xfer.list")["jobs"] if j["id"] == jid)
        if cond(j):
            return j
        time.sleep(0.3)
    raise SystemExit(f"timed out waiting on {jid}")


finished = lambda j: j["state"] in ("done", "failed", "cancelled")
c = None
proxy = None
try:
    start_server("a", PORT_A, home_a)
    start_server("b", PORT_B, home_b)
    proxy = subprocess.Popen([py, os.path.join(HERE, "net_fault_proxy.py"), "--target", str(PORT_B), "--listen", str(SLOW_B), "--up-bps", "3000000", "--down-bps", "3000000"], stdout=subprocess.PIPE, stderr=subprocess.STDOUT)
    proxy.stdout.readline()
    started["daemon"] = subprocess.Popen([kelpied, "serve"], env=os.environ.copy(), creationflags=0x08000000 if os.name == "nt" else 0, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    for _ in range(100):
        try:
            c = kc.Conn()
            break
        except OSError:
            time.sleep(0.1)
    check(c and c.call("daemon.info")["api"] >= 33, "daemon with host-to-host routes")

    src = os.path.join(home_a, "big.bin")
    with open(src, "wb") as f:
        for _ in range(48):
            f.write(os.urandom(1 << 20))
    dst_dir = os.path.join(home_b, "in")
    os.makedirs(dst_dir)

    # 1, 2: direct, and never with agent forwarding.
    jid = c.call("xfer.start", {"src": {"dest": "e2e-a"}, "dst": {"dest": "e2e-b"}, "items": [posix(src)], "dst_dir": posix(dst_dir), "conflict": "replace"})["id"]
    seen_forward_off = False
    for _ in range(50):
        cmds = [cmd for _, cmd in processes("ssh") if "e2e-a" in cmd and fwd(data).lower() in fwd(cmd).lower()]
        if cmds:
            seen_forward_off = all("ForwardAgent=no" in cmd for cmd in cmds)
            break
        time.sleep(0.2)
    j = wait_job(c, jid, finished)
    check(j["route_used"] == "direct" and j["state"] == "done" and sha(os.path.join(dst_dir, "big.bin")) == sha(src), f"direct A -> B, SHA-256 equal ({j['route_used']}: {j['route_reason']})")
    check(seen_forward_off, "the ssh to A has ForwardAgent=no, though its config says yes")

    # 3: cancel a direct copy (throttled): no partial on B, no sftp left for it.
    jid = c.call("xfer.start", {"src": {"dest": "e2e-a"}, "dst": {"dest": "e2e-b-slow"}, "items": [posix(src)], "dst_dir": posix(dst_dir), "conflict": "replace"})["id"]
    wait_job(c, jid, lambda j: j["totals"]["done_bytes"] > (2 << 20) or finished(j))
    c.call("xfer.control", {"id": jid, "action": "cancel"})
    wait_job(c, jid, finished)
    time.sleep(2)
    check(not any(n.endswith(".kelpie-part") for n in os.listdir(dst_dir)), "cancel leaves no partial on B")
    check(not [p for p, cmd in processes("sftp") if str(SLOW_B) in cmd], "no sftp left running on A for it")

    # 4: B goes away mid-copy and comes back: the direct copy resumes.
    os.remove(os.path.join(dst_dir, "big.bin"))
    jid = c.call("xfer.start", {"src": {"dest": "e2e-a"}, "dst": {"dest": "e2e-b-slow"}, "items": [posix(src)], "dst_dir": posix(dst_dir), "conflict": "replace"})["id"]
    wait_job(c, jid, lambda j: j["totals"]["done_bytes"] > (4 << 20))
    stop("b")
    wait_job(c, jid, lambda j: j["state"] == "reconnecting" or finished(j))
    start_server("b", PORT_B, home_b)
    j = wait_job(c, jid, finished, timeout=600)
    check(j["state"] == "done" and j["route_used"] == "direct" and sha(os.path.join(dst_dir, "big.bin")) == sha(src), "B came back: the direct copy resumed, SHA-256 equal")

    # 4b: an empty file and odd names: they arrive, and nothing in them ever runs.
    odd = os.path.join(home_a, "odd")
    os.makedirs(odd, exist_ok=True)
    names = ["empty.txt", "it's a (1).txt", "$(touch pwned) `touch pwned2`.txt"]
    for n in names:
        open(os.path.join(odd, n), "w").write("" if n == "empty.txt" else n)
    jid = c.call("xfer.start", {"src": {"dest": "e2e-a"}, "dst": {"dest": "e2e-b"}, "items": [posix(odd)], "dst_dir": posix(dst_dir), "conflict": "replace"})["id"]
    j = wait_job(c, jid, finished)
    landed = os.path.join(dst_dir, "odd")
    check(j["state"] == "done" and j["totals"]["failed"] == 0 and all(os.path.exists(os.path.join(landed, n)) for n in names), f"an empty file and odd names arrive ({j['route_used']}, failed {j['totals']['failed']})")
    check(os.path.getsize(os.path.join(landed, "empty.txt")) == 0, "the empty file is empty")
    pwned = [p for root in (home_a, home_b, scratch, os.getcwd()) for p in ("pwned", "pwned2") if os.path.exists(os.path.join(root, p))]
    check(not pwned, f"nothing in a name ran ({pwned})")

    # 5: A without a login of its own on B (its key gone): through this computer, with the reason.
    os.remove(key_a)
    os.remove(os.path.join(dst_dir, "big.bin"))
    jid = c.call("xfer.start", {"src": {"dest": "e2e-a"}, "dst": {"dest": "e2e-b-other"}, "items": [posix(src)], "dst_dir": posix(dst_dir), "conflict": "replace"})["id"]
    j = wait_job(c, jid, finished)
    check(j["route_used"] == "relay" and "no login of its own" in (j["route_reason"] or ""), f"relay with the reason ({j['route_reason']})")
    check(j["state"] == "done" and sha(os.path.join(dst_dir, "big.bin")) == sha(src), "through this computer, SHA-256 equal")
finally:
    if c is not None:
        try:
            c.call("daemon.shutdown")
        except (SystemExit, OSError):
            pass
    p = started.pop("daemon", None)
    if p:
        try:
            p.wait(15)
        except subprocess.TimeoutExpired:
            p.kill()
    for name in ("a", "b"):
        stop(name)
    if proxy and proxy.poll() is None:
        proxy.terminate()
    # ssh / sftp this run started (they name this run's config or ports) and that outlived it.
    left = [pid for pid, cmd in processes("ssh") if fwd(data).lower() in fwd(cmd).lower()] + [pid for pid, cmd in processes("sftp") if str(PORT_B) in cmd or str(SLOW_B) in cmd]
    for pid in left:
        subprocess.run(["taskkill", "/F", "/PID", str(pid)] if os.name == "nt" else ["kill", "-9", str(pid)], capture_output=True)
    check(not left, f"nothing of this run left running ({left})")

print("ALL PASS" if ok else "SOME FAILED", flush=True)
sys.exit(0 if ok else 1)
