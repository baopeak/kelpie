"""E2E for the daemon's file methods and transfer queue (no window).

    python -X utf8 scripts/e2e/sftp_files.py <kelpied.exe> <scratch-dir>

Sets its own KELPIE_ENDPOINT, KELPIE_DATA_DIR and KELPIE_SSH_DIR in this process before anything starts, and starts
its own `kelpied serve` with them: the real daemon and the real ~/.ssh are never touched. The "host" is
`ssh_test_server.py` (needs paramiko) on 127.0.0.1, logged in with a key made for this run; its throttled twin goes
through `net_fault_proxy.py`. Only the processes this script starts are stopped, by their own handles.

Covers: realpath / mkdir / list / rename / stat / chmod on a host, local.list, an unknown host key (ssh's own text),
upload and download with equal SHA-256, conflict ask -> keep both and apply-to-all, cancel leaving no partial, pause
and resume from the partial, the host going away mid-transfer and coming back (resumes by itself), a daemon restart
(the job shows interrupted, then resumes), delete and recursive chmod jobs.
"""
import hashlib
import importlib.util
import json
import os
import shutil
import subprocess
import sys
import time

kelpied, scratch = os.path.abspath(sys.argv[1]), os.path.abspath(sys.argv[2])
HERE = os.path.dirname(os.path.abspath(__file__))
PORT, SLOW_PORT = 47911, 47912

# Isolation first: everything below, and every child, sees only these.
os.environ["KELPIE_ENDPOINT"] = f"kelpie-e2e-sftp-{os.getpid()}"
data = os.path.join(scratch, "data")
ssh_dir = os.path.join(scratch, "ssh")
home = os.path.join(scratch, "home")
work = os.path.join(scratch, "work")
os.environ["KELPIE_DATA_DIR"] = data
os.environ["KELPIE_SSH_DIR"] = ssh_dir
for d in (data, ssh_dir, home, work):
    shutil.rmtree(d, ignore_errors=True)
    os.makedirs(d)
os.makedirs(os.path.join(home, ".ssh"))
os.makedirs(os.path.join(data, "ssh"))
if os.name == "nt":
    for d in (ssh_dir, os.path.join(data, "ssh")):
        subprocess.run(["icacls", d, "/inheritance:r", "/grant:r", f"{os.environ['USERNAME']}:(OI)(CI)F", "/grant:r", "SYSTEM:(OI)(CI)F", "/grant:r", "Administrators:(OI)(CI)F"], capture_output=True, check=True)

spec = importlib.util.spec_from_file_location("kelpie_call", os.path.join(HERE, "..", "kelpie-call.py"))
kc = importlib.util.module_from_spec(spec)
spec.loader.exec_module(kc)

ssh_keygen = os.path.join(os.environ.get("SystemRoot", r"C:\Windows"), "System32", "OpenSSH", "ssh-keygen.exe") if os.name == "nt" else "ssh-keygen"
key = os.path.join(ssh_dir, "id_e2e")
subprocess.run([ssh_keygen, "-q", "-t", "ed25519", "-N", "", "-f", key], check=True)
import paramiko  # noqa: E402
host_key = os.path.join(scratch, "host_key")
if not os.path.exists(host_key):
    paramiko.RSAKey.generate(2048).write_private_key_file(host_key)
hk = paramiko.RSAKey(filename=host_key).get_base64()
fwd = lambda p: p.replace("\\", "/")
q = lambda p: f'"{fwd(p)}"'
open(os.path.join(ssh_dir, "known_hosts"), "w").write(f"[127.0.0.1]:{PORT} ssh-rsa {hk}\ne2e-proxied ssh-rsa {hk}\n")
open(os.path.join(ssh_dir, "empty"), "w").close()
open(os.path.join(ssh_dir, "config"), "w").close()
auth = f"  User tester\n  IdentityFile {q(key)}\n  IdentitiesOnly yes\n  IdentityAgent none\n"
with open(os.path.join(data, "ssh", "config"), "w") as f:
    f.write("# Generated by Kelpie from hosts.json (here: by the e2e script).\n")
    f.write(f"\nHost e2e-host\n  HostName 127.0.0.1\n  Port {PORT}\n{auth}")
    f.write(f"\nHost e2e-slow\n  HostName 127.0.0.1\n  Port {SLOW_PORT}\n  HostKeyAlias e2e-proxied\n{auth}")
    f.write(f"\nHost e2e-unknown\n  HostName 127.0.0.1\n  Port {PORT}\n{auth}  UserKnownHostsFile {q(os.path.join(ssh_dir, 'empty'))}\n")
    f.write(f"\nMatch all\n  UserKnownHostsFile {q(os.path.join(ssh_dir, 'known_hosts'))}\n  GlobalKnownHostsFile {q(os.path.join(ssh_dir, 'empty'))}\nInclude {q(os.path.join(ssh_dir, 'config'))}\n")

py = os.environ.get("KELPIE_SSH_TEST_PYTHON", sys.executable)
started = {}


def start_server():
    p = subprocess.Popen([py, os.path.join(HERE, "ssh_test_server.py"), str(PORT), key + ".pub", host_key], env=dict(os.environ, KELPIE_TEST_HOME=home), stdout=subprocess.PIPE, stderr=subprocess.STDOUT)
    p.stdout.readline()
    started["server"] = p


def stop(name):
    p = started.pop(name, None)
    if p and p.poll() is None:
        p.terminate()
        try:
            p.wait(10)
        except subprocess.TimeoutExpired:
            p.kill()


def start_daemon():
    flags = 0x08000000 if os.name == "nt" else 0
    started["daemon"] = subprocess.Popen([kelpied, "serve"], env=os.environ.copy(), creationflags=flags, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    for _ in range(100):
        try:
            return kc.Conn()
        except OSError:
            time.sleep(0.1)
    raise SystemExit("the test daemon did not start")


def stop_daemon(c):
    try:
        c.call("daemon.shutdown")
    except (SystemExit, OSError):
        pass
    p = started.pop("daemon", None)
    if p:
        try:
            p.wait(15)
        except subprocess.TimeoutExpired:
            p.kill()


ok = True


def check(cond, what):
    global ok
    print(("PASS " if cond else "FAIL ") + what, flush=True)
    ok = ok and bool(cond)


def call_err(c, method, params):
    try:
        c.call(method, params)
        return None
    except SystemExit as e:
        return str(e)


def sha(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        while chunk := f.read(1 << 20):
            h.update(chunk)
    return h.hexdigest()


def make(path, mb):
    with open(path, "wb") as f:
        for _ in range(mb):
            f.write(os.urandom(1 << 20))


def posix(p):
    """The fixture serves this machine with Git Bash paths: C:\\x -> /c/x."""
    return "/" + p[0].lower() + fwd(p[2:]) if len(p) > 1 and p[1] == ":" else fwd(p)


def job(c, jid):
    return next(j for j in c.call("xfer.list")["jobs"] if j["id"] == jid)


def wait_job(c, jid, cond, timeout=180):
    end = time.time() + timeout
    while time.time() < end:
        j = job(c, jid)
        if cond(j):
            return j
        time.sleep(0.2)
    raise SystemExit(f"timed out waiting on {jid}: {job(c, jid)}")


finished = lambda j: j["state"] in ("done", "failed", "cancelled")

c = None
proxy = None
try:
    start_server()
    proxy = subprocess.Popen([py, os.path.join(HERE, "net_fault_proxy.py"), "--target", str(PORT), "--listen", str(SLOW_PORT), "--up-bps", "4000000", "--down-bps", "4000000"], stdout=subprocess.PIPE, stderr=subprocess.STDOUT)
    proxy.stdout.readline()
    c = start_daemon()
    info = c.call("daemon.info")
    check(info["api"] >= 27, f"daemon API {info['api']} has the file methods and the queue")

    # ---- browsing ----
    host_home = c.call("sftp.realpath", {"dest": "e2e-host", "path": "~"})["path"]
    check(host_home.startswith("/"), f"login folder {host_home}")
    remote_work = posix(work)
    c.call("sftp.mkdir", {"dest": "e2e-host", "path": remote_work + "/made"})
    names = {e["name"]: e for e in c.call("sftp.list", {"dest": "e2e-host", "path": remote_work})}
    check(names.get("made", {}).get("kind") == "dir", "mkdir then list")
    open(os.path.join(work, ".hidden"), "w").close()
    check(".hidden" not in {e["name"] for e in c.call("sftp.list", {"dest": "e2e-host", "path": remote_work})}, "hidden names only when asked")
    check(".hidden" in {e["name"] for e in c.call("sftp.list", {"dest": "e2e-host", "path": remote_work, "hidden": True})}, "hidden names when asked")
    c.call("sftp.rename", {"dest": "e2e-host", "from": remote_work + "/made", "to": remote_work + "/renamed"})
    check(os.path.isdir(os.path.join(work, "renamed")), "rename")
    open(os.path.join(work, "taken"), "w").close()
    check(call_err(c, "sftp.rename", {"dest": "e2e-host", "from": remote_work + "/renamed", "to": remote_work + "/taken"}) is not None, "rename refuses an existing target")
    st = c.call("sftp.stat", {"dest": "e2e-host", "path": remote_work + "/taken"})
    check(st["stat"]["kind"] == "file", "stat")
    check(any(e["name"] == "renamed" for e in c.call("local.list", {"path": work})), "local.list")
    err = call_err(c, "sftp.list", {"dest": "e2e-unknown", "path": "/"}) or ""
    check("Host key verification failed" in err, f"an unknown host key keeps ssh's text ({err[:80]})")
    check(call_err(c, "sftp.list", {"dest": "-oProxyCommand=x", "path": "/"}) is not None, "an option-like destination is refused")

    # ---- transfers ----
    big = os.path.join(scratch, "big.bin")
    make(big, 48)
    up_dir = os.path.join(work, "up")
    os.makedirs(up_dir)
    jid = c.call("xfer.start", {"src": {}, "dst": {"dest": "e2e-host"}, "items": [big], "dst_dir": posix(up_dir), "conflict": "ask"})["id"]
    j = wait_job(c, jid, finished)
    check(j["state"] == "done" and sha(os.path.join(up_dir, "big.bin")) == sha(big), "upload: done, SHA-256 equal")
    down_dir = os.path.join(scratch, "down")
    os.makedirs(down_dir)
    jid = c.call("xfer.start", {"src": {"dest": "e2e-host"}, "dst": {}, "items": [posix(os.path.join(up_dir, "big.bin"))], "dst_dir": down_dir})["id"]
    j = wait_job(c, jid, finished)
    check(j["state"] == "done" and sha(os.path.join(down_dir, "big.bin")) == sha(big), "download: done, SHA-256 equal")

    # Conflict: ask, then keep both.
    jid = c.call("xfer.start", {"src": {}, "dst": {"dest": "e2e-host"}, "items": [big], "dst_dir": posix(up_dir)})["id"]
    j = wait_job(c, jid, lambda j: j["questions"] or finished(j))
    check(bool(j["questions"]) and j["state"] == "waiting", "an existing target asks")
    c.call("xfer.answer", {"id": jid, "choice": "keep_both"})
    j = wait_job(c, jid, finished)
    check(os.path.exists(os.path.join(up_dir, "big (2).bin")), "keep both: big (2).bin")

    # Cancel mid-way through the throttled route: no partial is left.
    slow_dir = os.path.join(work, "slow")
    os.makedirs(slow_dir)
    jid = c.call("xfer.start", {"src": {}, "dst": {"dest": "e2e-slow"}, "items": [big], "dst_dir": posix(slow_dir), "conflict": "replace"})["id"]
    wait_job(c, jid, lambda j: j["totals"]["done_bytes"] > (2 << 20) or finished(j))
    c.call("xfer.control", {"id": jid, "action": "cancel"})
    wait_job(c, jid, finished)
    time.sleep(1)
    check(not any(n.endswith(".kelpie-part") for n in os.listdir(slow_dir)), "cancel leaves no partial")

    # Pause, then resume from the partial.
    jid = c.call("xfer.start", {"src": {}, "dst": {"dest": "e2e-slow"}, "items": [big], "dst_dir": posix(slow_dir), "conflict": "replace"})["id"]
    wait_job(c, jid, lambda j: j["totals"]["done_bytes"] > (4 << 20))
    c.call("xfer.control", {"id": jid, "action": "pause"})
    j = wait_job(c, jid, lambda j: j["state"] == "paused")
    partial = os.path.join(slow_dir, ".big.bin.kelpie-part")
    kept = os.path.getsize(partial) if os.path.exists(partial) else 0
    check(kept > 0, f"pause keeps the partial ({kept} bytes)")
    c.call("xfer.control", {"id": jid, "action": "resume"})
    j = wait_job(c, jid, finished, timeout=300)
    check(j["state"] == "done" and sha(os.path.join(slow_dir, "big.bin")) == sha(big), "resume: done, SHA-256 equal")

    # The host goes away mid-transfer and comes back: the job reconnects and resumes by itself.
    os.remove(os.path.join(slow_dir, "big.bin"))
    jid = c.call("xfer.start", {"src": {}, "dst": {"dest": "e2e-slow"}, "items": [big], "dst_dir": posix(slow_dir), "conflict": "replace"})["id"]
    wait_job(c, jid, lambda j: j["totals"]["done_bytes"] > (4 << 20))
    stop("server")
    j = wait_job(c, jid, lambda j: j["state"] == "reconnecting" or finished(j))
    check(j["state"] == "reconnecting", f"a lost host shows reconnecting (attempt {j['attempt']})")
    start_server()
    j = wait_job(c, jid, finished, timeout=300)
    check(j["state"] == "done" and sha(os.path.join(slow_dir, "big.bin")) == sha(big), "reconnected and resumed: SHA-256 equal")

    # A daemon restart: the job shows interrupted, then resumes.
    os.remove(os.path.join(slow_dir, "big.bin"))
    jid = c.call("xfer.start", {"src": {}, "dst": {"dest": "e2e-slow"}, "items": [big], "dst_dir": posix(slow_dir), "conflict": "replace"})["id"]
    wait_job(c, jid, lambda j: j["totals"]["done_bytes"] > (4 << 20))
    stop_daemon(c)
    c = start_daemon()
    j = job(c, jid)
    check(j["state"] == "interrupted", f"after a restart: {j['state']}")
    c.call("xfer.control", {"id": jid, "action": "resume"})
    j = wait_job(c, jid, finished, timeout=300)
    check(j["state"] == "done" and sha(os.path.join(slow_dir, "big.bin")) == sha(big), "resumed after the restart: SHA-256 equal")

    # A folder: recursive chmod, then delete (children first; the folder is gone).
    tree = os.path.join(work, "tree")
    os.makedirs(os.path.join(tree, "sub"))
    for n in ("a.txt", os.path.join("sub", "b.txt")):
        open(os.path.join(tree, n), "w").write(n)
    jid = c.call("xfer.start", {"kind": "chmod", "src": {"dest": "e2e-host"}, "items": [posix(tree)], "mode": 0o640, "dirs_only_x": True})["id"]
    j = wait_job(c, jid, finished)
    check(j["state"] == "done" and j["totals"]["failed"] == 0, "recursive chmod job")
    jid = c.call("xfer.start", {"kind": "delete", "src": {"dest": "e2e-host"}, "items": [posix(tree)]})["id"]
    j = wait_job(c, jid, finished)
    check(j["state"] == "done" and not os.path.exists(tree), "delete job removes the folder")
    c.call("xfer.clear_finished")
    check(all(not finished(j) for j in c.call("xfer.list")["jobs"]), "clear finished")
finally:
    if c is not None:
        stop_daemon(c)
    stop("daemon")
    stop("server")
    if proxy and proxy.poll() is None:
        proxy.terminate()
        try:
            proxy.wait(5)
        except subprocess.TimeoutExpired:
            proxy.kill()

print("ALL PASS" if ok else "SOME FAILED", flush=True)
sys.exit(0 if ok else 1)
